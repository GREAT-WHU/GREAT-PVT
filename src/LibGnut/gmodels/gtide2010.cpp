    std::vector<double> libiers_spline(int NN, Eigen::MatrixXd X, Eigen::MatrixXd U, Eigen::MatrixXd A)
    {
        int N = abs(NN);
        std::vector<double> S;
        if (N <= 3)
        {
            for (int I = 1; I <= N; I++)
            {
                S.push_back(0.0);
            }
            return S;
        }
        double U1 = U(0, 1) - U(0, 0);
        double X1 = X(0, 1) - X(0, 0);
        double U2 = U(0, 2) - U(0, 0);
        double X2 = X(0, 2) - X(0, 0);
        double Q1 = (U1 / X1 / X1 - U2 / X2 / X2) / (1.0 / X1 - 1.0 / X2);
        U1 = U(0, N - 2) - U(0, N - 1);
        X1 = X(0, N - 2) - X(0, N - 1);
        U2 = U(0, N - 3) - U(0, N - 1);
        X2 = X(0, N - 3) - X(0, N - 1);
        double QN = (U1 / X1 / X1 - U2 / X2 / X2) / (1.0 / X1 - 1.0 / X2);
        if (NN <= 0)
        {
            Q1 = S[0];
            QN = S[1];
        }
        S.push_back(6.0 * ((U(0, 1) - U(0, 0)) / (X(0, 1) - X(0, 0)) - Q1));
        int N1 = N - 1;
        for (int I = 2; I <= N1; I++)
        {
            S.push_back((U(0, I - 2) / (X(0, I - 1) - X(0, I - 2)) - U(0, I - 1) * (1.0 / (X(0, I - 1) - X(0, I - 2)) + 1.0 / (X(0, I) - X(0, I - 1))) +
                         U(0, I) / (X(0, I) - X(0, I - 1))) *
                        6.0);
        }
        S.push_back(6.0 * (QN + (U(0, N1 - 1) - U(0, N - 1)) / (X(0, N - 1) - X(0, N1 - 1))));
        A(0, 0) = 2.0 * (X(0, 1) - X(0, 0));
        A(0, 1) = 1.5 * (X(0, 1) - X(0, 0)) + 2.0 * (X(0, 2) - X(0, 1));
        S[1] = S[1] - 0.5 * S[0];
        double C;
        for (int I = 3; I <= N1; I++)
        {
            C = (X(0, I - 1) - X(0, I - 2)) / A(0, I - 2);
            A(0, I - 1) = 2.0 * (X(0, I) - X(0, I - 2)) - C * (X(0, I - 1) - X(0, I - 2));
            S[I - 1] = S[I - 1] - C * S[I - 2];
        }
        C = (X(0, N - 1) - X(0, N1 - 1)) / A(0, N1 - 1);
        A(0, N - 1) = (2.0 - C) * (X(0, N - 1) - X(0, N1 - 1));
        S[N - 1] = S[N - 1] - C * S[N1 - 1];
        S[N - 1] = S[N - 1] / A(0, N - 1);
        for (int J = 1; J <= N1; J++)
        {
            int I = N - J;
            S[I - 1] = (S[I - 1] - (X(0, I) - X(0, I - 1)) * S[I]) / A(0, I - 1);
        }
        return S;
    }

    Eigen::MatrixXd libiers_eval(std::vector<double> Y, int NN, Eigen::MatrixXd X, Eigen::MatrixXd U, std::vector<double> S)
    {
        unsigned int nt = Y.size();
        Eigen::MatrixXd EVAL = Eigen::MatrixXd::Zero(nt, 1);
        std::vector<double> id1;
        for (unsigned int I = 0; I < nt; I++)
        {
            if (Y[I] <= X(0, 0))
            {
                id1.push_back(I + 1);
            }
        }
        if (!id1.empty())
        {
            for (unsigned int I = 0; I < id1.size(); I++)
            {
                EVAL(id1[I] - 1, 0) = U(0, 0);
            }
        }

        std::vector<double> id2;
        for (unsigned int I = 0; I < nt; I++)
        {
            if (Y[I] >= X(0, NN - 1))
            {
                id2.push_back(I + 1);
            }
        }
        if (!id2.empty())
        {
            for (unsigned int I = 0; I < id2.size(); I++)
            {
                EVAL(id2[I] - 1, 0) = U(0, NN - 1);
            }
        }

        std::vector<double> YY;
        bool findid1 = false, findid2 = false;
        for (unsigned int i = 0; i < Y.size(); i++)
        {
            for (unsigned int m = 0; m < id1.size(); m++)
            {
                if (id1[m] == i + 1)
                {
                    findid1 = true;
                    break;
                }
            }
            if (findid1 == false)
            {
                for (unsigned int m = 0; m < id2.size(); m++)
                {
                    if (id2[m] == i + 1)
                    {
                        findid2 = true;
                        break;
                    }
                }
            }
            if (findid1 == false && findid2 == false)
            {
                YY.push_back(Y[i]);
            }
            else
            {
                findid1 = false;
                findid2 = false;
            }
        }

        double lY = YY.size();
        Eigen::MatrixXd K1 = Eigen::MatrixXd::Zero(1, lY);
        Eigen::MatrixXd K2 = Eigen::MatrixXd::Zero(1, lY);
        for (unsigned int i = 1; i <= lY; i++)
        {
            for (int K = 2; K <= NN; K++)
            {
                if (X(0, K - 2) < YY[i - 1] && X(0, K - 1) >= YY[i - 1])
                {
                    K1(0, i - 1) = K - 1;
                    K2(0, i - 1) = K;
                }
            }
        }

        std::vector<double> DY, DY1, DK, DELI, FF1, FF2, F1, F2, F3, EVAL1;
        for (unsigned int I = 0; I < YY.size(); I++)
        {
            DY.push_back(X(0, int(K2(0, I)) - 1) - YY[I]);
            DY1.push_back(YY[I] - X(0, int(K1(0, I)) - 1));
            DK.push_back(X(0, int(K2(0, I)) - 1) - X(0, int(K1(0, I)) - 1));
            DELI.push_back(1.0 / (6.0 * DK[I]));
            FF1.push_back(S[int(K1(0, I)) - 1] * pow(DY[I], 3));
            FF2.push_back(S[int(K2(0, I)) - 1] * pow(DY1[I], 3));
            F1.push_back((FF1[I] + FF2[I]) * DELI[I]);
            F2.push_back(DY1[I] * (U(0, int(K2(0, I)) - 1) / DK[I] - S[int(K2(0, I)) - 1] * DK[I] / 6.0));
            F3.push_back(DY[I] * (U(0, int(K1(0, I)) - 1) / DK[I] - S[int(K1(0, I)) - 1] * DK[I] / 6.0));
            EVAL1.push_back(F1[I] + F2[I] + F3[I]);
        }

        findid1 = false;
        findid2 = false;
        unsigned int n1 = 0;
        for (unsigned int i = 1; i <= nt; i++)
        {
            for (unsigned int m = 0; m < id1.size(); m++)
            {
                if (id1[m] == i)
                {
                    findid1 = true;
                    break;
                }
            }
            if (findid1 == false)
            {
                for (unsigned int m = 0; m < id2.size(); m++)
                {
                    if (id2[m] == i)
                    {
                        findid2 = true;
                        break;
                    }
                }
            }
            if (findid1 == false && findid2 == false)
            {
                EVAL(i - 1, 0) = EVAL1[n1];
                n1++;
            }
            else
            {
                findid1 = false;
                findid2 = false;
            }
        }

        return EVAL;
    }

