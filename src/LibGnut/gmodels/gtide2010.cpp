    double null2pi_degree(double angle)
    {
        while (angle > 360.0)
        {
            angle -= 360.0;
        }
        while (angle < 0)
        {
            angle += 360.0;
        }
        return angle;
    }

    double null2pi_rad(double angle)
    {
        while (angle > 2 * G_PI)
        {
            angle -= 2 * G_PI;
        }
        while (angle < 0)
        {
            angle += 2 * G_PI;
        }
        return angle;
    }

    Eigen::MatrixXd DD_arguments(double mjd, double delta)
    {
        Eigen::MatrixXd Kij(5, 5), Doodson0(6, 5), Doodson(6, 5); // general
        Eigen::VectorXd tM(5), Delauney(6), Doodson_vec(6), Doodson_vecf(12), fund_freqDood(6);
        Eigen::RowVectorXd l(5), ls(5), F(5), D(5), Om(5), s(5), h(5), p(5), Ns(5), ps(5), T(5);
        double t0, t1, t2, t3, t4;

        // nulling
        Doodson0.setZero();
        Delauney.setZero();
        Doodson_vec.setZero();

        t0 = 1.0;
        t1 = (mjd - 51544.5 + delta / 86400.0) / 36525.0; // 51544.5 vs. 51545.0.... double T = (dmjd - 51545.0 + delta/86400.0)/36525.0;
        t2 = pow(t1, 2);
        t3 = pow(t1, 3);
        t4 = pow(t1, 4);
        tM << t0, t1, t2, t3, t4;

        // IERS 2010, p.67 ... l, l', F, D, Omega (F1 ... F5)
        Kij << 134.96340251, 357.52910918, 93.27209062, 297.85019547, 125.04455501, 1717915923.2178 / 3600
, 129596581.0481 / 3600, 1739527262.8478 / 3600, 1602961601.2090 / 3600, -6962890.5431 / 3600          // /3600;
, 31.8792 / 3600, -0.5532 / 3600, -12.7512 / 3600, -6.3706 / 3600, 7.4722 / 3600                     // /3600;
, 0.051635 / 3600, 0.000136 / 3600, -0.001037 / 3600, 0.006593 / 3600, 0.007702 / 3600               // /3600;
, -0.00024470 / 3600, -0.00001149 / 3600, 0.00000417 / 3600, -0.00003169 / 3600, -0.00005939 / 3600; // /3600;

        // Delauney arguments, IERS 2010 p.48
        l = Kij.col(0).transpose();
        ls = Kij.col(1).transpose();
        F = Kij.col(2).transpose();
        D = Kij.col(3).transpose();
        Om = Kij.col(4).transpose();

        //  Doodson arguments, Dehant (2015) et al., p.178
        s = F + Om;            // mean lunar node
        h = F + Om - D;        // angle of the mean tropic year
        p = -l + F + Om;       // mean lunar perigee
        Ns = -Om;              // angle of the mean lunar node
        ps = -ls + F + Om - D; // angle of perihelion - ps/p'
        T = -s;                // -s [+ gmst + pi] ... added below

        // Delauney
        Delauney << T.dot(tM), l.dot(tM), ls.dot(tM), F.dot(tM), D.dot(tM), Om.dot(tM);
        Delauney = Delauney * D2R;

        // Doodson0 ... T is not ready here!
        Doodson0.row(0) = T;
        Doodson0.row(1) = s;
        Doodson0.row(2) = h;
        Doodson0.row(3) = p;
        Doodson0.row(4) = Ns;
        Doodson0.row(5) = ps;

        // Doodson fundamental frequencies
        fund_freqDood = Doodson0.col(1) / 36525.0 / 24.0; // in [degree/hour] in mean Solar day
        fund_freqDood(0) = 15.0 - fund_freqDood(1) + fund_freqDood(2);

        // Doodson ... final modification
        Doodson = Doodson0;
        // convert to <0,360)
        for (int i = 0; i < 6; ++i)
        {
            Doodson(i, 0) = null2pi_degree(Doodson(i, 0));
        }

        // make a vector
        Doodson_vec = Doodson * tM;

        // get GMST
        t_gephplan epoGMST;
        double gmst_i = R2D * epoGMST.gmst(mjd);

        // update T for [+ gmst + pi]!
        Doodson_vec(0) = Doodson_vec(0) + gmst_i + 180.0;

        // convert to <0,360) and put to Doodson_vecf
        Doodson_vecf(0) =
            D2R *
            null2pi_degree(Doodson_vec(0)); // zde se diky starsi funkci GMST v gephplan.h lisime na 8 des. miste (nema vliv na vysledek)
        for (int i = 1; i < 6; ++i)
        {
            Doodson_vecf(i) = D2R * null2pi_degree(Doodson_vec(i));
        }

        // add frequencies
        Doodson_vecf.tail(6) = fund_freqDood;

        return Doodson_vecf;
    }

